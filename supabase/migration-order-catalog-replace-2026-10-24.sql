declare clash text;
begin
  if to_regclass('public.order_barcode_moves') is not null then
    execute 'select string_agg(m.old_barcode, '', '') from public.order_barcode_moves m join new_catalog n on n.barcode = m.old_barcode' into clash;
    if clash is not null then
      raise exception '승인된 바코드 변경의 옛 바코드가 새 목록에 있어 중단합니다 (사장님이 정리 필요): %', clash;
    end if;
  end if;
end $$;

