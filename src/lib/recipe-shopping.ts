/** 웬만한 집에 다 있는 기본 양념 — 부족 재료 맨 뒤로, 흐리게 보인다. */
export const STAPLES = new Set([
  '소금', '설탕', '후추', '깨', '참기름', '식용유', '간장', '국간장', '고춧가루', '식초', '물엿', '올리고당',
]);

export interface MissingIngredient {
  name: string;
  staple: boolean;
}

/** 레시피 재료 중 보관 중인 상품으로 갖고 있지 않은 것. 기본 양념은 뒤로. */
export function missingIngredients(recipeName: string, haveNames: string[]): MissingIngredient[] {
  const entry = RECIPE_SHOPPING[recipeName];
  if (!entry) return [];
  const have = haveNames.map(normalizeName);
  const missing = entry.buy
    .filter((item) => {
      // "소고기 국거리"처럼 띄어 쓴 검색어는 첫 단어로 갖고 있는지 본다
      const key = normalizeName(item.split(' ')[0]);
      return !have.some((h) => ingredientMatches(h, key));
    })
    .map((name) => ({ name, staple: STAPLES.has(name) }));
  return [...missing.filter((m) => !m.staple), ...missing.filter((m) => m.staple)];
}
