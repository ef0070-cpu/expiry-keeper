/** 설정에서 고르는 그림 */
export const TILE_ART_CHOICES = ART.map(([e]) => e);

/** 사장님이 고른 그림이 있으면 그것, 없으면 이름 속 맛 단어로 정한 그림, 없으면 null */
export function tileArt(name: string, override?: string | null): string | null {
  if (override && TILE_ART_CHOICES.includes(override)) return override;
  for (const [emoji, words] of ART) if (words.some((w) => name.includes(w))) return emoji;
  return null;
}
