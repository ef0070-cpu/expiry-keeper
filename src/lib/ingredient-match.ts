// 상품명 ↔ 레시피 키워드 매칭 보조.
// 사용자가 적는 상품명은 "국내산 냉동 삼겹살 500g (행사)"처럼 잡음이 많아서,
// 그대로 includes() 하면 '삼겹' 같은 키워드도 곧잘 빗나간다.
// 여기서 이름을 정규화하고 표기 변형(동의어)을 흡수한다.
// 이 파일은 의존성이 없어야 한다 — scripts/check-recipe-match.mjs가 직접 import 한다.

/** 용량·수량 단위. 숫자 뒤에 붙은 것만 지운다. */
const QTY = /\d+(?:[.,]\d+)?\s*(?:kg|g|ml|l|리터|개입|개|입|봉지|봉|팩|매|장|인분|마리|미|과|병|캔|줄|포|쪽|단|호)/g;

/** 상품명에 흔히 붙는 수식어. 지워도 재료 뜻이 남는 것만. */
const NOISE = [
  '무항생제', '무가당', '무설탕', '무염', '무농약', '무첨가', '유기농', '친환경',
  '국내산', '수입산', '산지직송', '신선', '특가', '행사', '대용량', '냉장', '냉동',
  '생물', '손질', '자연산', '프리미엄',
];

/** 소문자화 + 괄호·기호·공백·용량·수식어 제거 */
export function normalizeName(raw: string): string {
  let s = raw.toLowerCase();
  s = s.replace(/[([{<][^)\]}>]*[)\]}>]/g, ''); // (대), [1+1] 같은 괄호 표기
  s = s.replace(QTY, '');
  s = s.replace(/[^0-9a-z가-힣]/g, ''); // 공백·기호 제거
  for (const n of NOISE) s = s.split(n).join('');
  return s;
}

