/** 정규화된 상품명이 키워드(또는 그 표기 변형)를 품고 있는가 */
export function ingredientMatches(normalizedName: string, keyword: string): boolean {
  if (normalizedName.includes(keyword)) return true;
  const alts = SYNONYMS[keyword];
  return alts !== undefined && alts.some((a) => normalizedName.includes(a));
}
